"""
Required data passing classes
"""
from __future__ import annotations

from datetime import datetime
from typing import Union, Any
from enum import Enum
from dataclasses import dataclass, field
import uuid

class SignalType(Enum):
    BUY = 1
    SELL = 2

class OrderType(Enum):
    MARKET = 1
    BRACKET = 2
    STOP_LOSS = 3
    PROFIT_TAKER = 4

class OrderAction(Enum):
    BUY = 1
    SELL = 2

class OrderStatus(Enum):
    PENDING = 0
    FILLED = 1
    CANCELED = 2
    PENDING_SALE = 3

class OrderTimeInForce(Enum):
    DAY = 1 # For the day
    GTC = 2 # Good til Canceled
    IOC = 3 # Immediate or Cancel
    FOK = 4 # Fill or Kill
    OPG = 5 # At the open
    CLS = 6 # At the close

@dataclass
class PriceData:
    symbol: str
    timestamp: datetime
    open: float
    high: float
    low: float
    close: float
    volume: float
    trade_count: int = None
    vwap: float = None
    exchange: float = None

    @classmethod
    def from_dict(cls, data: dict, timestamp: datetime=None):
        """Create a PriceData instance from a dictionary."""
        if timestamp is not None:
            data['timestamp'] = timestamp
        return cls(**data)

@dataclass
class Position:
    symbol: str
    quantity: int

@dataclass
class MarketSignal:
    type: SignalType
    symbol: str
    strength: int # 0-100 to indicate how strong the signal is
    metadata: dict[str, Any] = field(default_factory=dict)

@dataclass
class TickResults:
    orders: list[Order] =  field(default_factory=lambda: []) # Orders generated by the portfolio for this tick
    output_tick: list[PriceData] = None # If the tick was changed it can be here, None otherwise
    metadata: dict[str, Any] = field(default_factory=dict)
    # Bracket orders to trigger manual sale on. Base class will set MANUAL_SALE=True,
    # call OM update, and apply portfolio changes if filled instantly.
    trigger_manual_sales: list[BracketOrder] = field(default_factory=lambda: [])
    # Cancel all pending orders of these types before submitting new orders.
    cancel_pending_order_types: list[OrderType] = field(default_factory=lambda: [])

@dataclass
class Order:
    placed_datetime: datetime
    action: OrderAction
    type: OrderType
    symbol: str
    price: float
    quantity: int
    cash: float
    executed_datetime: Union[None, datetime] = None
    time_in_force: OrderTimeInForce = OrderTimeInForce.GTC
    status: OrderStatus = OrderStatus.PENDING
    order_id: str = field(default_factory=lambda: f"local-{str(uuid.uuid4())}")
    tx_cost: float = 0.0
    parent_id: str = None
    platform_id: str = None
    _child_orders: list[str] = field(default_factory=lambda: [])
    _child_orders_dict: dict[str, Order] = field(default_factory=lambda: {})
    processed_by_portfolio: bool = False

    def __str__(self):
        return (f"Order {self.order_id}: status: {self.status} {self.symbol}: {self.type} "
                f"quantity: {self.quantity} price: {self.price} "
                f"placed: {self.placed_datetime} executed: {self.executed_datetime} "
                f"processed by portfolio: {self.processed_by_portfolio}")

    def add_child_order(self, name: str, order: Union[None, Order]):
        if name not in self._child_orders:
            self._child_orders.append(name)
        self._child_orders_dict[name] = order

    def get_child_order_names(self) -> list[str]:
        return list(self._child_orders_dict.keys())

    def get_child_order(self, name: str) -> Order:
        return self._child_orders_dict[name]

    @staticmethod
    def create_market_order(
            symbol: str,
            order_action: OrderAction,
            quantity: int,
            tx_cost: float=0.0,
            current_tick:list[PriceData]=None,
    ) -> Order:
        """Create a MarketOrder instance."""
        if current_tick is not None:
            # Find the PriceData for this symbol
            pd = next((x for x in current_tick if x.symbol == symbol), None)
            placed_ts = pd.timestamp if pd else datetime.now()
        else:
            placed_ts = datetime.now()

        ret_val = Order(
            action=order_action,
            status=OrderStatus.PENDING,
            type=OrderType.MARKET,
            symbol=symbol,
            price=0.0,
            quantity=quantity,
            cash=0.0,
            tx_cost=tx_cost,
            placed_datetime=placed_ts,
        )
        return ret_val



